"""Системный промпт: общие правила чтения нарядов + справочник клиентов."""

from naryad.clients import Clients

RULES = """Ты распознаёшь бумажные заказ-наряды зуботехнической лаборатории по фото.
Бланки разных клиник выглядят по-разному, часто заполнены от руки и небрежно.

Правила:
- Возвращай то, что написано, а не то, что «должно быть». Итог не пересчитывай.
- Зачёркнутое значение игнорируй, бери то, что написано рядом взамен.
- Пустое поле или прочерк — null (для списков — пустой список). Ничего не выдумывай.
- Зубная формула крестом: врач рисует крест, как будто смотрит пациенту в рот.
  Четверть слева сверху = 1x, справа сверху = 2x, справа снизу = 3x, слева снизу = 4x;
  в четверти пишут только вторую цифру. «6» в правой нижней четверти = зуб 36.
- Даты без года — год берётся из даты наряда. Формат ответа ГГГГ-ММ-ДД.
- Если поле видно, но прочитать уверенно нельзя — верни лучшую догадку и внеси имя поля в unreadable."""


def clients_section(clients: Clients) -> str:
    lines = [f"- {clinic}: {', '.join(doctors)}" for clinic, doctors in clients.items()]
    return (
        "Клиенты лаборатории (клиника: врачи):\n" + "\n".join(lines) + "\n"
        "Если клиника или врач на фото похожи на кого-то из списка — верни написание из списка. "
        "Если не похожи ни на кого — верни как написано и внеси поле в unreadable. "
        "Не подставляй значение из списка, если на фото оно не написано."
    )


def build_system_prompt(clients: Clients) -> str:
    return RULES + "\n\n" + clients_section(clients)
